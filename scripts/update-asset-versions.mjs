#!/usr/bin/env node
/*
 * Recomputes the content versions of the static CSS and JavaScript referenced by index.html and
 * rules.html: every URL gets ?v=<first 12 hex of the file's SHA-256>, and index.html's module
 * block (import map, module preloads, entry script) is regenerated from the files in static/js.
 *
 * Run from the repository root after editing any CSS or JS:
 *     node scripts/update-asset-versions.mjs
 *
 * tests/unit/seo.test.js fails when a version is stale. The backend derives the CSP hash of the
 * import map from the packaged index.html at startup, so no other file needs updating.
 */
import {createHash} from "node:crypto";
import {readFileSync, readdirSync, writeFileSync} from "node:fs";
import {join} from "node:path";

const STATIC_DIR = "src/main/resources/static";
const ENTRY = "main.js";
const BLOCK_START = "<!-- ES modules: generated by scripts/update-asset-versions.mjs -->";
const BLOCK_END = "<!-- /ES modules -->";

function version(assetPath) {
    return createHash("sha256").update(readFileSync(join(STATIC_DIR, assetPath))).digest("hex").slice(0, 12);
}

const versioned = assetPath => `/${assetPath}?v=${version(assetPath)}`;

function moduleBlock() {
    const modules = readdirSync(join(STATIC_DIR, "js")).filter(f => f.endsWith(".js") && f !== ENTRY).sort();
    const imports = modules.map(f => `    "/js/${f}": "${versioned(`js/${f}`)}"`).join(",\n");
    return [
        BLOCK_START,
        `<script type="importmap">\n{\n  "imports": {\n${imports}\n  }\n}\n</script>`,
        ...modules.map(f => `<link rel="modulepreload" href="${versioned(`js/${f}`)}">`),
        `<script type="module" src="${versioned(`js/${ENTRY}`)}"></script>`,
        BLOCK_END
    ].join("\n");
}

for (const page of ["index.html", "rules.html"]) {
    const file = join(STATIC_DIR, page);
    const original = readFileSync(file, "utf8");
    let html = original.replace(
        /((?:href|src)="\/)((?:css|js)\/[\w.-]+\.(?:css|js))\?v=[a-f0-9]{12}"/g,
        (match, prefix, assetPath) => `${prefix}${assetPath}?v=${version(assetPath)}"`
    );
    const start = html.indexOf(BLOCK_START);
    const end = html.indexOf(BLOCK_END);
    if (start >= 0 && end > start) {
        html = html.slice(0, start) + moduleBlock() + html.slice(end + BLOCK_END.length);
    }
    if (html !== original) {
        writeFileSync(file, html);
        console.log(`updated ${page}`);
    } else {
        console.log(`${page} is up to date`);
    }
}
